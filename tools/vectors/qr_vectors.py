"""Writes shared/src/commonTest/kotlin/circles/qr/QrVectors.kt: QR codes made by the independent `qrcode` library
(byte mode, error correction M, border 0) for several texts and every mask (the mask is fixed, so only the structure is compared; the choice of mask by penalty is ours), as hex rows, to compare with circles.qr.QrCode.
Run with a Python that has qrcode installed:  python tools/vectors/qr_vectors.py"""
import qrcode, qrcode.constants, qrcode.util, sys, pathlib

TEXTS = {
    "hello": "HELLO",
    "v3": "https://circles.example/#/item/0123456789abcdef",
    "v6": "https://circles.example.org/#/verify/00112233445566778899aabbccddeeff/ffeeddccbbaa99887766554433221100/ab12 cd34 ef56 7890 1234",
    "v8": "https://circles.example.org/#/verify/00112233445566778899aabbccddeeff/ffeeddccbbaa99887766554433221100/ab12 cd34 ef56 7890 1234?x=" + "0123456789" * 4 + "end",
    "v10": ("Circles " + "0123456789abcdef" * 13)[:213],
    "unicode": "Caf\u00e9 \u20ac \u2713",
}

def matrix(text, mask):
    qr = qrcode.QRCode(version=None, error_correction=qrcode.constants.ERROR_CORRECT_M, border=0, mask_pattern=mask)
    qr.add_data(qrcode.util.QRData(text, mode=qrcode.util.MODE_8BIT_BYTE))
    qr.make(fit=True)
    rows = qr.get_matrix()
    return qr.version, ["".join("1" if m else "0" for m in row) for row in rows]

def hexrows(rows):
    out = []
    for r in rows:
        padded = r + "0" * (-len(r) % 4)
        out.append(format(int(padded, 2), "0{}x".format(len(padded) // 4)))
    return "/".join(out)

lines = ["package circles.qr", "", "// Generated by tools/vectors/qr_vectors.py from the independent `qrcode` library. Do not edit.", "",
         "class QrVector(val text: String, val version: Int, val size: Int, val mask: Int, val rows: String)", "",
         "val QR_VECTORS: List<QrVector> = listOf("]
for name, text in TEXTS.items():
    for mask in range(8):
        version, rows = matrix(text, mask)
        esc = text.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$").replace("\u00e9", "\\u00e9").replace("\u20ac", "\\u20ac").replace("\u2713", "\\u2713")
        lines.append(f'    QrVector("{esc}", {version}, {len(rows)}, {mask}, "{hexrows(rows)}"),')
lines.append(")")
path = pathlib.Path(__file__).resolve().parents[2] / "shared/src/commonTest/kotlin/circles/qr/QrVectors.kt"
path.parent.mkdir(parents=True, exist_ok=True)
path.write_text("\n".join(lines) + "\n")
print("wrote", path, len(lines), "lines")
